#!/usr/bin/env node
// Generates docs/tools.md from the tool schemas declared by the MCP server,
// so the reference can never drift from the code.
// Usage: node scripts/generate-tool-docs.js [--check]
const fs = require('node:fs');
const path = require('node:path');

// Neutralise environment-dependent defaults so the output is reproducible.
delete process.env.OPENROUTER_DEFAULT_MODEL;
const { TOOLS, VERSION } = require('../plugins/openrouter/server/index.js');

const OUT = path.join(__dirname, '..', 'docs', 'tools.md');
const esc = (s = '') => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

function typeOf(schema) {
  if (schema.enum) return schema.enum.map((v) => `\`${v}\``).join(' \\| ');
  if (schema.type === 'array') return `${schema.items?.type === 'object' ? 'object' : schema.items?.type || 'any'}[]`;
  return schema.type || 'any';
}

function constraints(schema) {
  const c = [];
  if (schema.minimum != null) c.push(`min ${schema.minimum}`);
  if (schema.maximum != null) c.push(`max ${schema.maximum}`);
  if (schema.default != null) c.push(`default \`${JSON.stringify(schema.default)}\``);
  return c.length ? ` (${c.join(', ')})` : '';
}

function render() {
  const lines = [
    '# Tool reference',
    '',
    '<!-- Generated by scripts/generate-tool-docs.js — do not edit by hand. Run `npm run docs`. -->',
    '',
    `MCP tools exposed by the \`openrouter\` server (plugin version ${VERSION}). In Claude Code they appear as`,
    '`mcp__plugin_openrouter_openrouter__<tool>`; you normally just describe what you want and Claude picks the tool.',
    '',
    '| Tool | Summary |',
    '| --- | --- |',
    ...TOOLS.map((t) => `| [\`${t.name}\`](#${t.name}) | ${esc(t.description.split('. ')[0])}. |`),
    '',
  ];
  for (const t of TOOLS) {
    lines.push(`## \`${t.name}\``, '', t.description, '');
    const props = Object.entries(t.inputSchema.properties || {});
    if (!props.length) {
      lines.push('_No parameters._', '');
      continue;
    }
    const required = new Set(t.inputSchema.required || []);
    lines.push('| Parameter | Type | Required | Description |', '| --- | --- | --- | --- |');
    for (const [name, schema] of props) {
      lines.push(`| \`${name}\` | ${typeOf(schema)} | ${required.has(name) ? 'yes' : 'no'} | ${esc(schema.description || '')}${constraints(schema)} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

const content = render();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== content) {
    console.error('docs/tools.md is out of date. Run `npm run docs`.');
    process.exit(1);
  }
  console.log('docs/tools.md is up to date.');
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, content);
  console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
}
